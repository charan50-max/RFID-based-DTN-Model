"""
Train and export the tiny decision-tree model used by the RFID DTN demo.

This is a transparent synthetic training task, not a production priority model.
Run: python train_model.py
It regenerates tinyml_model.json and arduino/RFID_DTN_TinyML/TinyMLModel.h
"""
import itertools
import json
from pathlib import Path
from sklearn.tree import DecisionTreeClassifier, _tree

ROOT = Path(__file__).resolve().parent
X, y = [], []
for severity, deadline, event_type in itertools.product(range(3), repeat=3):
    # Demonstration target rule used to generate labels for training.
    score = severity * 3 + (2 - deadline) * 2 + event_type
    label = 1 if score >= 9 else (2 if score >= 5 else 3)
    X.append([severity, deadline, event_type])
    y.append(label)

model = DecisionTreeClassifier(max_depth=5, random_state=42)
model.fit(X, y)

def to_dict(node=0):
    tree = model.tree_
    if tree.feature[node] == _tree.TREE_UNDEFINED:
        counts = tree.value[node][0]
        return {"class": int(model.classes_[int(counts.argmax())])}
    return {
        "feature": int(tree.feature[node]),
        "threshold": float(tree.threshold[node]),
        "left": to_dict(int(tree.children_left[node])),
        "right": to_dict(int(tree.children_right[node])),
    }

tree_json = {
    "features": ["severity", "deadline", "event_type"],
    "classes": {"1": "CRITICAL", "2": "HIGH", "3": "NORMAL"},
    "training_accuracy_on_synthetic_combinations": round(float(model.score(X, y)), 4),
    "training_note": "Small decision tree trained on 27 synthetic feature combinations. Not validated for real-world safety decisions.",
    "tree": to_dict(),
}
(ROOT / "tinyml_model.json").write_text(json.dumps(tree_json, indent=2), encoding="utf-8")

def emit(node, indent=1):
    pad = "  " * indent
    if "class" in node:
        return f"{pad}return {node['class']};"
    return (
        f"{pad}if (features[{node['feature']}] <= {node['threshold']:.1f}f) {{\n"
        f"{emit(node['left'], indent + 1)}\n"
        f"{pad}}} else {{\n"
        f"{emit(node['right'], indent + 1)}\n"
        f"{pad}}}"
    )

header = """#ifndef TINYML_MODEL_H
#define TINYML_MODEL_H
#include <stdint.h>
// Generated by train_model.py. Feature order: severity, deadline, event_type.
// Output class: 1=CRITICAL, 2=HIGH, 3=NORMAL.
static uint8_t predictPriority(const uint8_t features[3]) {
"""
header += emit(tree_json["tree"]) + "\n}\n#endif\n"
out = ROOT / "arduino" / "RFID_DTN_TinyML" / "TinyMLModel.h"
out.write_text(header, encoding="utf-8")
print("Model trained and exported.")
print("Synthetic training accuracy:", tree_json["training_accuracy_on_synthetic_combinations"])
print("Generated:", ROOT / "tinyml_model.json")
print("Generated:", out)
